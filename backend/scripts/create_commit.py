#!/usr/bin/env python3
import argparse
import base64
import binascii
import json
import secrets
import sys
from pathlib import Path
from typing import Any

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from pydantic import ValidationError

from app.schemas.intent import Intent
from app.services.canonical import commitment_hash

"""
python3 -m scripts.create_commit samples/sample_1.json --private-key 'BASE64_PRIVATE_KEY'
"""


def load_private_key(encoded: str) -> Ed25519PrivateKey:
    try:
        raw = base64.b64decode(encoded, validate=True)
    except (binascii.Error, ValueError) as exc:
        raise ValueError("--private-key must be valid Base64") from exc

    if len(raw) == 32:
        return Ed25519PrivateKey.from_private_bytes(raw)

    try:
        private_key = serialization.load_der_private_key(raw, password=None)
    except (TypeError, ValueError) as exc:
        raise ValueError(
            "--private-key must contain a supported Ed25519 private key"
        ) from exc

    if not isinstance(private_key, Ed25519PrivateKey):
        raise ValueError("--private-key must contain an Ed25519 key")
    return private_key


def read_intent(path: str) -> Intent:
    source = sys.stdin.read() if path == "-" else Path(path).read_text(encoding="utf-8")
    return Intent.model_validate_json(source)


def create_bundle(intent: Intent, private_key: Ed25519PrivateKey) -> dict[str, Any]:
    intent_data = intent.model_dump(mode="json", exclude_none=True)
    nonce = secrets.token_bytes(32)
    digest = commitment_hash(intent_data, nonce)
    signature = private_key.sign(digest)

    return {
        "domain": intent.domain,
        "commit_request": {
            "hash": base64.b64encode(digest).decode("ascii"),
            "signature": base64.b64encode(signature).decode("ascii"),
        },
        "reveal_request": {
            "intent": intent_data,
            "nonce": base64.b64encode(nonce).decode("ascii"),
        },
    }


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Create a signed DNS Intent commit/reveal bundle"
    )
    parser.add_argument("intent", help="Path to Intent JSON, or - for stdin")
    parser.add_argument(
        "--private-key",
        required=True,
        help=(
            "Base64 Ed25519 private key generated by the frontend, or a "
            "legacy raw 32-byte key."
        ),
    )
    args = parser.parse_args()

    try:
        intent = read_intent(args.intent)
        private_key = load_private_key(args.private_key)
        bundle = create_bundle(intent, private_key)
    except (OSError, ValueError, ValidationError) as exc:
        parser.error(str(exc))

    print(json.dumps(bundle, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
